import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname } from "node:path";
import { fileURLToPath } from "node:url";

/** Inlines spec/catalogue-limits.txt (synced from the DropHawk website) into src/generated/catalogue-limits.ts. */
const SOURCE = fileURLToPath(new URL("../../../spec/catalogue-limits.txt", import.meta.url));
const TARGET = fileURLToPath(new URL("../src/generated/catalogue-limits.ts", import.meta.url));

/** One bullet per line: the website wraps its bullets, a model reads them better unwrapped. */
function unwrap(text: string): string {
  return text
    .trim()
    .split("\n")
    .reduce<string[]>((bullets, line) => {
      if (line.startsWith("- ") || bullets.length === 0) bullets.push(line.trim());
      else bullets[bullets.length - 1] += ` ${line.trim()}`;
      return bullets;
    }, [])
    .join("\n");
}

const next = `/**
 * GENERATED FILE - DO NOT EDIT.
 * Generated by \`bun run generate\` from spec/catalogue-limits.txt, so the published package needs no spec file at runtime.
 */

export const CATALOGUE_LIMITS = ${JSON.stringify(unwrap(readFileSync(SOURCE, "utf8")), null, 2)};
`;

if (process.argv.includes("--check")) {
  const current = existsSync(TARGET) ? readFileSync(TARGET, "utf8") : "";
  if (current !== next) {
    console.error("src/generated/catalogue-limits.ts is stale. Run `bun run generate` in packages/mcp and commit the result.");
    process.exit(1);
  }
  console.log("src/generated/catalogue-limits.ts is up to date.");
} else {
  mkdirSync(dirname(TARGET), { recursive: true });
  writeFileSync(TARGET, next);
  console.log("wrote src/generated/catalogue-limits.ts");
}
